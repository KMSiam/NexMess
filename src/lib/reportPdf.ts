import jsPDF from 'jspdf'
import autoTable from 'jspdf-autotable'
import { format, startOfMonth, endOfMonth } from 'date-fns'

/**
 * Shared finance report PDF builder.
 *
 * Used by:
 *   - FinancePage   (live current-month data)
 *   - HistoryPage   (archived monthly_reports.summary JSON)
 *
 * Both call this single function so the two reports stay visually identical.
 */

export interface ReportMemberRow {
  username: string
  status?: 'pending' | 'approved' | 'left'
  meals: number
  mealCost: number
  deposited: number
}

export interface ReportFixedCostRow {
  description: string
  amount: number
}

export interface ReportSettlement {
  from: string
  to: string
  amount: number
}

export interface ReportData {
  messName: string
  month: string // 'YYYY-MM'
  generatedBy?: string // username, or 'Auto'/'Manager'
  isArchived?: boolean // header wording
  // Global summary
  totalExpenses: number
  totalDeposits: number
  totalFixed: number
  mealRate: number
  totalMeals: number
  // Rows
  financeMembersCount: number // for per-person fixed-cost split
  members: ReportMemberRow[]
  fixedCosts: ReportFixedCostRow[]
  settlements: ReportSettlement[]
}

const tk = (n: number) => `Tk ${Number(n || 0).toFixed(2)}`

/**
 * Builds the report PDF and triggers a browser download.
 */
export function buildReportPdf(data: ReportData): void {
  const doc = new jsPDF()

  // ── Header ──────────────────────────────────────────
  const [yy, mm] = data.month.split('-').map(Number)
  const monthDate = new Date(yy, (mm || 1) - 1, 1)
  const startDate = startOfMonth(monthDate)
  const endDate = endOfMonth(monthDate)
  const durationStr = `${format(startDate, 'dd MMM yyyy')} to ${format(endDate, 'dd MMM yyyy')}`

  doc.setFontSize(20)
  doc.text(`${data.messName} - Finance Report`, 14, 22)
  doc.setFontSize(11)
  doc.setTextColor(100)
  doc.text(`Duration: ${durationStr} | Generated by: ${data.generatedBy || 'Manager'}`, 14, 30)
  if (data.isArchived) {
    doc.setTextColor(16, 185, 129)
    doc.text(`(Archived monthly report — ${format(monthDate, 'MMMM yyyy')})`, 14, 37)
  }

  // ── Global Summary ──────────────────────────────────
  doc.setTextColor(0)
  doc.setFontSize(12)
  doc.text(`Total Meals Served: ${data.totalMeals}`, 14, 45)
  doc.text(`Meal Rate: ${tk(data.mealRate)}`, 14, 51)
  doc.text(`Total Bazaar Expenses: ${tk(data.totalExpenses)}`, 110, 45)
  doc.text(`Total Deposits Collected: ${tk(data.totalDeposits)}`, 110, 51)

  // ── Fixed Costs ─────────────────────────────────────
  let startY = 63
  if (data.fixedCosts.length > 0) {
    autoTable(doc, {
      startY,
      head: [['Fixed Cost Description', 'Amount']],
      body: data.fixedCosts.map((fc) => [fc.description, tk(fc.amount)]),
      foot: [['Total Fixed Costs', tk(data.totalFixed)]],
      theme: 'grid',
      headStyles: { fillColor: [59, 130, 246] },
    })
    startY = (doc as any).lastAutoTable.finalY + 15
  }

  // ── Member Breakdowns ───────────────────────────────
  const perPersonFixedCost =
    data.financeMembersCount > 0 ? data.totalFixed / data.financeMembersCount : 0

  autoTable(doc, {
    startY,
    head: [['Member', 'Meals', 'Meal Cost', 'Fixed Cost', 'Total Exp', 'Deposited', 'Balance']],
    body: data.members.map((m) => {
      const totalExp = m.mealCost + perPersonFixedCost
      const realBalance = m.deposited - totalExp
      return [
        (m.username || 'Unknown') + (m.status === 'left' ? ' (Left)' : ''),
        m.meals.toString(),
        tk(m.mealCost),
        tk(perPersonFixedCost),
        tk(totalExp),
        tk(m.deposited),
        tk(realBalance),
      ]
    }),
    theme: 'grid',
    headStyles: { fillColor: [15, 23, 42] },
    columnStyles: { 6: { fontStyle: 'bold' } },
  })

  // ── Settle-up sheet ─────────────────────────────────
  if (data.settlements.length > 0) {
    const settleY = (doc as any).lastAutoTable.finalY + 12
    autoTable(doc, {
      startY: settleY,
      head: [['Settle-up — who pays whom']],
      body: [],
      theme: 'plain',
      headStyles: { fillColor: [16, 185, 129], textColor: 255, fontSize: 12 },
    })
    autoTable(doc, {
      startY: (doc as any).lastAutoTable.finalY,
      head: [['From (debtor)', '', 'To (creditor)', 'Amount']],
      body: data.settlements.map((t) => [t.from, '->', t.to, `Tk ${t.amount.toFixed(0)}`]),
      theme: 'grid',
      headStyles: { fillColor: [16, 185, 129] },
      columnStyles: { 1: { halign: 'center' }, 3: { halign: 'right', fontStyle: 'bold' } },
    })
  }

  const safeName = data.messName.replace(/\s+/g, '_')
  doc.save(`NexMess_${safeName}_Report_${data.month}.pdf`)
}

/**
 * Compute the greedy minimum-transfers settle-up sheet from a list of members.
 * Mirrors the original FinancePage algorithm so live + archived reports match.
 */
export function computeSettlements(
  members: ReportMemberRow[],
  perPersonFixed: number
): ReportSettlement[] {
  const creditors: { name: string; amount: number }[] = []
  const debtors: { name: string; amount: number }[] = []
  members.forEach((m) => {
    const totalExp = m.mealCost + perPersonFixed
    const realBalance = m.deposited - totalExp
    const name = m.username || 'Member'
    if (realBalance > 0.5) creditors.push({ name, amount: realBalance })
    else if (realBalance < -0.5) debtors.push({ name, amount: -realBalance })
  })
  creditors.sort((a, b) => b.amount - a.amount)
  debtors.sort((a, b) => b.amount - a.amount)
  const transfers: ReportSettlement[] = []
  let i = 0,
    j = 0
  while (i < debtors.length && j < creditors.length) {
    const amt = Math.min(debtors[i].amount, creditors[j].amount)
    transfers.push({ from: debtors[i].name, to: creditors[j].name, amount: Math.round(amt) })
    debtors[i].amount -= amt
    creditors[j].amount -= amt
    if (debtors[i].amount < 0.5) i++
    if (creditors[j].amount < 0.5) j++
  }
  return transfers
}
